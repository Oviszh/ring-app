const test = require('node:test')
const assert = require('node:assert/strict')
const d = require('../miniprogram/services/domain')
const at = (day, hour=8, minute=0) => new Date(2026,9,day,hour,minute).getTime()
function setup(type='count') { const s=d.createInitialState(at(21)); const p=d.createPractice(s,{name:'功课',type,dailyTarget:108},at(21)); return {s,p} }
test('目标当天多次修改仍用原快照，次日才生效；当日快照不重复汇总',()=>{
 const {s,p}=setup(); d.addEntry(s,{practiceId:p.id,date:'2026-10-21',amount:108,ts:at(21)})
 d.setDailyTarget(s,p.id,500,at(21));d.setDailyTarget(s,p.id,1000,at(21))
 assert.equal(d.dayTotals(s,'2026-10-21',p.id).target,108)
 assert.equal(d.practiceTotalsAll(s,p.id).total,108)
 d.settleUpTo(s,at(22));assert.equal(d.dayTotals(s,'2026-10-22',p.id).target,1000)
 assert.equal(d.dayTotals(s,'2026-10-21',p.id).target,108)
})
test('创建前没有未完成日；删除后过去达标记录保留',()=>{
 const {s,p}=setup();assert.equal(d.calendarDayStatus(s,'2026-10-20'),'none')
 d.addEntry(s,{practiceId:p.id,date:'2026-10-21',amount:108,ts:at(21)})
 d.removePractice(s,p.id,at(21));d.settleUpTo(s,at(23))
 assert.equal(d.calendarDayStatus(s,'2026-10-21'),'met')
 assert.equal(d.calendarDayStatus(s,'2026-10-22'),'none')
})
test('跨零点撤销只撤昨天本轮点按，修正后来源不能变负',()=>{
 const {s,p}=setup();d.startNewRound(s,'phone',p.id,{ts:at(21,23,50)});d.tap(s,'phone',at(21,23,50),3)
 d.undoTap(s,'phone',at(22,0,10));assert.equal(d.dayTotals(s,'2026-10-21',p.id).phone,2)
 assert.equal(d.dayTotals(s,'2026-10-22',p.id).phone,0)
 d.addAdjustment(s,{practiceId:p.id,date:'2026-10-21',source:'phone',toValue:0,ts:at(22)})
 assert.equal(d.undoTap(s,'phone',at(22)).undone,false)
})
test('禅坐跨日展示、结束一致，无重复时长；背景暂停不计入时长',()=>{
 const {s,p}=setup('time');d.startNewRound(s,'phone',p.id,{ts:at(21,23,50)})
 d.pausePhone(s,at(21,23,55));d.resumePhone(s,at(22,0,5))
 assert.equal(d.dayTotals(s,'2026-10-21',p.id).durationMin,5)
 assert.equal(d.dayTotals(s,'2026-10-22',p.id,at(22,0,10)).durationMin,5)
 assert.equal(d.elapsedMs(s.contexts.phone,at(22,0,10)),10*60000)
 d.endRound(s,'phone',at(22,0,10));assert.equal(d.practiceTotalsAll(s,p.id).durationMin,10)
 assert.equal(d.practiceTotalsAll(s,p.id).times,1)
})
test('计时型填报分钟和座数可整笔撤销，归档前后相同',()=>{
 const {s,p}=setup('time');const e=d.addEntry(s,{practiceId:p.id,date:'2026-10-21',amount:30,ts:at(21)})
 assert.equal(d.dayTotals(s,'2026-10-21',p.id).durationMin,30)
 assert.equal(d.dayTotals(s,'2026-10-21',p.id).times,1)
 d.settleUpTo(s,at(22));assert.equal(d.practiceTotalsAll(s,p.id).durationMin,30)
 d.undoEntry(s,e.id);assert.equal(d.practiceTotalsAll(s,p.id).durationMin,0)
})
test('非法日期、小数、无穷输入拒绝，禅坐不接受次数提醒',()=>{
 const {s,p}=setup('time')
 for(const amount of [Infinity,NaN,0,-1,1.5]) assert.throws(()=>d.addEntry(s,{practiceId:p.id,date:'2026-10-21',amount,ts:at(21)}))
 assert.throws(()=>d.addEntry(s,{practiceId:p.id,date:'2026-02-30',amount:1,ts:at(21)}))
 assert.throws(()=>d.startNewRound(s,'phone',p.id,{ts:at(21),reminder:{type:'count',value:108}}))
})
test('备份完整校验、来回恢复不改总量，坏文件拒绝',()=>{
 const {s,p}=setup();d.addEntry(s,{practiceId:p.id,date:'2026-10-21',amount:10,ts:at(21)})
 const backup=require('../miniprogram/services/domain/backup')
 const text=backup.exportBackup(s,at(21));const restored=backup.importBackup(text)
 assert.equal(d.practiceTotalsAll(restored,p.id).total,10)
 assert.throws(()=>backup.importBackup(text.replace('nianfo-backup','wrong')))
 const obj=JSON.parse(text);obj.payload+=' ';assert.throws(()=>backup.importBackup(JSON.stringify(obj)))
})
